const HAS_KANJI = /\p{Script=Han}/u
const SKIP_TAGS = new Set(['RUBY', 'RT', 'RP', 'SCRIPT', 'STYLE', 'TEXTAREA', 'SELECT', 'OPTION'])

export const createFuriganaEntries = (trains) => {
  const entries = new Map()
  Object.entries(UI_READINGS).forEach(([text, reading]) => entries.set(text, reading))
  Object.entries(REGION_READINGS).forEach(([text, reading]) => entries.set(text, reading))
  Object.entries(OPERATOR_READINGS).forEach(([text, reading]) => entries.set(text, reading))
  Object.entries(LINE_READINGS).forEach(([text, reading]) => entries.set(text, reading))
  trains.forEach((train) => entries.set(train.name, train.reading))
  return [...entries.entries()]
    .filter(([text, reading]) => HAS_KANJI.test(text) && reading)
    .sort(([a], [b]) => b.length - a.length)
}

export const readingForText = (text, entries) => entries.find(([label]) => label === text)?.[1] ?? ''

export const applyFurigana = (root, entries) => {
  const textNodes = []
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  while (walker.nextNode()) {
    const node = walker.currentNode
    if (!node.textContent.trim() || SKIP_TAGS.has(node.parentElement?.tagName)) continue
    if (!HAS_KANJI.test(node.textContent)) continue
    textNodes.push(node)
  }

  textNodes.forEach((node) => {
    const fragment = document.createDocumentFragment()
    let remaining = node.textContent
    let changed = false

    while (remaining) {
      let bestIndex = -1
      let bestText = ''
      let bestReading = ''

      entries.forEach(([text, reading]) => {
        const index = remaining.indexOf(text)
        if (index < 0) return
        if (bestIndex < 0 || index < bestIndex || (index === bestIndex && text.length > bestText.length)) {
          bestIndex = index
          bestText = text
          bestReading = reading
        }
      })

      if (bestIndex < 0) {
        fragment.append(document.createTextNode(remaining))
        break
      }
      if (bestIndex > 0) fragment.append(document.createTextNode(remaining.slice(0, bestIndex)))

      const ruby = document.createElement('ruby')
      ruby.append(document.createTextNode(bestText))
      const rpOpen = document.createElement('rp')
      rpOpen.textContent = '（'
      const rt = document.createElement('rt')
      rt.textContent = bestReading
      const rpClose = document.createElement('rp')
      rpClose.textContent = '）'
      ruby.append(rpOpen, rt, rpClose)
      fragment.append(ruby)
      remaining = remaining.slice(bestIndex + bestText.length)
      changed = true
    }

    if (changed) node.replaceWith(fragment)
  })
}

